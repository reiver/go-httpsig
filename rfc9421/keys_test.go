func pemBytes(t *testing.T, s string) []byte {
	t.Helper()

	block, _ := pem.Decode([]byte(s))
	if nil == block {
		t.Fatal("Expected a PEM block.")
	}
	return block.Bytes
}

func testKeyRSAPublic(t *testing.T) *rsa.PublicKey {
	key, err := x509.ParsePKCS1PublicKey(pemBytes(t, testKeyRSAPublicPEM))
	if nil != err {
		t.Fatalf("Did not expect an error but actually got one: (%T) %s", err, err)
	}
	return key
}

